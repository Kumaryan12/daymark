const assert = require('node:assert/strict');
const m = require('../dist/model.js');
const parse = (text, date, sender) => m.parse(text,'test',{sentAt:date,sender})[0];
const old = parse('Campus accounts\nRef CF-104\nPlease pay semester fees of ₹2,500 by 20 November 2026.','2026-11-15T10:00','Campus accounts');
let items=m.merge([],old,'fees').items;
let follow=parse('Guys, semester fees extended to Friday.','2026-11-18T11:30','Campus accounts');
follow=m.dateEvidence(follow);
assert.equal(follow.due,'2026-11-20');
const ranks=m.matchCandidates(items,follow);
assert.equal(ranks[0].id,'fees');
assert.ok(ranks[0].evidence.some(e=>e.includes('topic')));
assert.equal(m.matchAction(items,follow),null);
const updated=parse('Guys, semester fees extended to Friday.','2026-11-21T11:30','Campus accounts');
const revised=m.dateEvidence({...updated,targetId:'fees'});
assert.equal(revised.due,'2026-11-27');
items[0].reminder={time:'09:00'};
items=m.merge(items,revised,'change').items;
assert.equal(items[0].due,'2026-11-20');
items=m.resolve(items,'fees',true);
assert.equal(items[0].due,'2026-11-27');
assert.equal(items[0].reminder.time,'09:00');
assert.equal(items[0].source.sentAt,'2026-11-21T11:30');
assert.equal(m.merge(items,{...old,targetId:'fees'},'duplicate').items.length,1);
assert.equal(m.merge(items,{...old,targetId:'fees'},'duplicate').change,'unchanged');
const earlier=parse('Campus accounts\nPlease pay semester fees by 21 November 2026.','2026-11-16T10:00','Campus accounts');
const archived=m.merge(items,{...earlier,targetId:'fees'},'older');
assert.equal(archived.change,'archived');
assert.equal(archived.items[0].due,'2026-11-27');
assert.equal(archived.items[0].pending,null);
const alternate={...old,title:'Pay laboratory fees',id:'lab',source:{...old.source,text:'Laboratory fees are ₹1,000.'},reference:'LF-8',amount:'1000'};
const ambiguous=m.matchCandidates([items[0],alternate],parse('Guys, extended to Friday.','2026-11-18T11:00','Campus accounts'));
assert.equal(ambiguous.length,2);
assert.equal(m.relativeDate('tomorrow','2026-12-31T23:00').due,'2027-01-01');
assert.equal(m.relativeDate('Friday',''),null);
assert.equal(m.parse('Return your book by 05\nDecember 2026.')[0].due,'2026-12-05');
console.log('Model regression checks passed: fuzzy evidence, relative dates, ambiguous matches, chronological history, deduplication, reminder date changes.');
